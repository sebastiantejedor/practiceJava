package POO;

public class Student {
    String name;
    long code;
    int age;
    String semester;

    void displayInfo() {
        System.out.println("POO.Student Information:");
        System.out.println("Name: " + name);
        System.out.println("Code: " + code);
        System.out.println("Age: " + age);
        System.out.println("Semester: " + semester);
    }
}
